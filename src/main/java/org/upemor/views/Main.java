    /**
     * Muestra el dashboard correspondiente según el rol del usuario autenticado.
     * Si el usuario es estudiante, abre el dashboard de estudiante; si es empleado/admin, abre el menú de administración.
     * @param usuario Usuario autenticado
     */
    public void mostrarDashboard(Usuarios usuario) {
        if (usuario == null) return;
        // Selecciona el dashboard según el rol
        JFrame dashboard = usuario.getRol().equals("estudiante") ? new Dashboard(usuario) : new MenuAdmin(usuario);
        // Cierra la ventana actual y muestra el dashboard
        this.dispose();
        dashboard.setVisible(true);
    }

