    /**
     * Cambia el color del botón seleccionado y restablece el de los demás.
     * @param boton Botón que fue seleccionado
     */
    private void seleccionarBoton(JButton boton) {
        bttnEmpleado.setBackground(Colores.CONTRA_FONDO);
        bttnEmpleado.setForeground(Colores.TEXTO_TENUE);
        bttnEstudiante.setBackground(Colores.CONTRA_FONDO);
        bttnEstudiante.setForeground(Colores.TEXTO_TENUE);
        boton.setBackground(Colores.PRIMARIO);
        boton.setForeground(Colores.TEXTO);
    }


    /**
     * Muestra el panel recibido en el área principal de la ventana.
     * @param panel Panel a mostrar (formulario de acceso)
     */
    private void mostrarContenido(JPanel panel) {
        layerPanel.removeAll();
        layerPanel.add(panel);
        layerPanel.revalidate();
        layerPanel.repaint();
    }


