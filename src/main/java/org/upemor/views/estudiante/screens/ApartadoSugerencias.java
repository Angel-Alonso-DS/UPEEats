    /**
     * Acción al presionar el botón de agregar sugerencia.
     * Valida los campos y registra la sugerencia en la base de datos.
     */
    private void bttnAgregarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_bttnAgregarActionPerformed
        if (idUsuario == 0) return;
        String asunto = campoAsunto.getText();
        String comentario = campoComentario.getText();
        try {
            Validadores.validarTexto(comentario);
            Validadores.validarTexto(comentario);
            sugerenciasCTR.insertar(idUsuario, asunto, comentario);
            campoAsunto.setText("");
            campoComentario.setText("");
            cargarVista();
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, e.getMessage(), "Campo invalido", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_bttnAgregarActionPerformed


