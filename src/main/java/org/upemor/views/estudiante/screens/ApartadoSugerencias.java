    /**
     * Método que recibe notificaciones globales para editar o eliminar sugerencias.
     * @param msg Mensaje recibido
     * @param objetos Objetos relacionados con el mensaje
     */
    @Override
    public void onReceptor(String msg, Object[] objetos) {
        if (framePadre == null) return;
        if (msg.equals("edicion Sugerencias")) {
            // Muestra el formulario de edición de sugerencia en un diálogo modal
            Sugerencias sugerencia = (Sugerencias) objetos[0];
            JDialog dialogo = new JDialog(framePadre, "Editar", true);
            dialogo.setSize(600,600);
            dialogo.setLocationRelativeTo(this);
            dialogo.add(new FormularioSugerencia(this, dialogo, sugerencia));
            dialogo.setVisible(true);
        }
        if (msg.equals("eliminacion Sugerencias")) {
            // Confirma y elimina la sugerencia seleccionada
            Sugerencias sugerencia = (Sugerencias) objetos[0];
            int OK = JOptionPane.showConfirmDialog(this, "Seguro?", "Eliminar sugerencia", JOptionPane.YES_NO_OPTION);
            if (OK == 1) return;
            sugerenciasCTR.eliminar(sugerencia.getId());
            cargarVista();
        }
    }
