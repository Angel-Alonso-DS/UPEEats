    /**
     * Constructor. Inicializa componentes, registra el panel como receptor de notificaciones
     * y configura la lista de sugerencias en modo solo lectura.
     */
    public PantallaSugerencias() {
        // Registrar este panel para recibir notificaciones globales
        NotificadorGlobal.getInstancia().registrar(this);
        sugerenciasCTR = new SugerenciasControlador();
        initComponents();
        
        // Configurar la lista para solo mostrar detalles, sin edición ni eliminación
        panelListaEntidades.setVistaDetalles();
        panelListaEntidades.tieneEdicion(false);
        panelListaEntidades.tieneEliminacion(false);
        
        // Cargar todas las sugerencias al iniciar
        cargarVista();
        
        // Configurar acción de búsqueda en el encabezado
        encabezado.setBusquedaAccion(t -> {
            panelListaEntidades.actualizarLista(sugerenciasCTR.buscarPorAsunto(t));
        });
    }


    /**
     * Carga y muestra todas las sugerencias en el panel de lista.
     */
    public void cargarVista() {
        panelListaEntidades.actualizarLista(sugerenciasCTR.obtenerTodos());
    }

