    /**
     * Método que responde a notificaciones globales.
     * <ul>
     *   <li>"actualizar lista Sugerencias": Recarga la lista de sugerencias.</li>
     *   <li>"detalle Sugerencias": Muestra un diálogo modal con el detalle de la sugerencia seleccionada.</li>
     * </ul>
     * @param msg Mensaje de notificación recibido.
     * @param objetos Parámetros adicionales enviados con la notificación.
     */
    @Override
    public void onReceptor(String msg, Object[] objetos) {
        if (msg.equals("actualizar lista Sugerencias")) {
            cargarVista();
        }

        if (msg.equals("detalle Sugerencias")) {
            Sugerencias sugerencia = (Sugerencias) objetos[0];
            JDialog dialogo = new JDialog(framePadre, "Detalle sugerencia", true);

            // Se establece el tamaño del diálogo
            dialogo.setSize(600,600);

            // Se centra el diálogo respecto a la ventana principal
            dialogo.setLocationRelativeTo(this);

            // Se agrega el panel de detalle de sugerencia al diálogo
            dialogo.add(new VistaSugerencia(dialogo, sugerencia));
            dialogo.setVisible(true);
        }
    }
