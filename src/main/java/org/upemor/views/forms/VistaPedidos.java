    @Override
    public void onReceptor(String msg, Object[] objetos) {
        if (msg.equals("agregar Carrito")) {
            panelListaEntidades.actualizarLista(listaCarrito);
        }

        if (msg.equals("detalle ItemDetallePedido")) {
            ItemDetallePedido itm = (ItemDetallePedido) objetos[0];
            Productos producto = itm.getProducto();
            JDialog dialog = new JDialog(SwingUtilities.getWindowAncestor(this), "Ver producto", JDialog.ModalityType.APPLICATION_MODAL);
            
            int cantidad = itm.getCantidad();
            System.out.println("Detalle Pedido");
            VistaProducto vistaProducto = new VistaProducto(dialog, producto, cantidad, itm.getObservacion());

            dialog.setSize(800, 800);
            dialog.add(vistaProducto);
            dialog.setLocationRelativeTo(this);
            dialog.setVisible(true);
        }

        if (msg.equals("eliminar ItemDetallePedido") || msg.equals("eliminacion ItemDetallePedido")) {
            ItemDetallePedido itm = (ItemDetallePedido) objetos[0];
            
            for (int i = 0; i < listaCarrito.size(); i++) {
                ItemDetallePedido item = listaCarrito.get(i);
                
                if (item.getProducto().getId() == itm.getProducto().getId()) {
                    listaCarrito.remove(i);
                    break;
                }
            }
            if (listaCarrito.size() < 1) {
                bttnBorrar.setEnabled(false);
                bttnRealizarPedido.setEnabled(false);
            }
            panelListaEntidades.actualizarLista(listaCarrito);
            calcularTotal();
        }
    }
