    private void bttnRealizarPedidoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_bttnRealizarPedidoActionPerformed
        if (listaCarrito.size() < 1) {
            JOptionPane.showMessageDialog(this, "No hay productos en el carrito");
            return;
        }

        int OK = JOptionPane.showConfirmDialog(this, "Seguro que quieres pedir ya?", "Realizar pedido", JOptionPane.YES_NO_OPTION);

        if (OK == JOptionPane.NO_OPTION) return;

        try {
            String comentario = campoMensaje.getText();

            if (comentario.isEmpty()) comentario = "Sin comentarios";

            if (usuario == null) {
                JOptionPane.showMessageDialog(this, "Debes iniciar sesión para realizar un pedido");
                return;
            }

            pedidosCTR.crearPedido(usuario, listaCarrito, comentario);
            
            listaCarrito.clear();
            panelListaEntidades.actualizarLista(listaCarrito);
            textoTotal.setText("$0.0");
            campoMensaje.setText("");
            
            NotificadorGlobal.getInstancia().notificarCambio("actualizacion de Pedido", new Object[] {});

            JOptionPane.showMessageDialog(this, "Pedido realizado con éxito");
            
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error al realizar el pedido: " + e.getMessage());
            System.err.println(e);
            e.printStackTrace();
        }
        
        dialogo.setVisible(false);
        NotificadorGlobal.getInstancia().remover(this);
    }//GEN-LAST:event_bttnRealizarPedidoActionPerformed

    private void bttnBorrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_bttnBorrarActionPerformed
        int OK = JOptionPane.showConfirmDialog(this, "Seguro que quieres borrar el carrito?", "Borrar carrito", JOptionPane.YES_NO_OPTION);

        if (OK == JOptionPane.YES_OPTION) {
            listaCarrito.clear();
            panelListaEntidades.actualizarLista(listaCarrito);
            bttnBorrar.setEnabled(false);
            bttnRealizarPedido.setEnabled(false);
            textoTotal.setText("$0.0");
            campoMensaje.setText("");
            
            NotificadorGlobal.getInstancia().notificarCambio("borrar Pedido", new Object[] {});
        }
    }//GEN-LAST:event_bttnBorrarActionPerformed


