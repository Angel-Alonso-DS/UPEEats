    // Evento botón cerrar: Oculta el diálogo que contiene esta vista
    private void bttnCerrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_bttnCerrarActionPerformed
        dialogo.setVisible(false);
        if (cantidad > 0 || actualCantidad != cantidad) {
            NotificadorGlobal.getInstancia().notificarCambio("agregar Carrito", new Object[] {new ItemDetallePedido(producto, cantidad, total, campoObservaciones.getText())});
        }
    }//GEN-LAST:event_bttnCerrarActionPerformed

    private void bttnMasActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_bttnMasActionPerformed
        cantidad++;

        if (cantidad >= 50) {
            bttnMas.setEnabled(false);
            campoObservaciones.setEditable(false);
            calcularMostrarCantidad();
            return;
        }
        

        if (cantidad > 0) {
            bttnMenos.setEnabled(true);
            campoObservaciones.setEditable(true);
        }

        calcularMostrarCantidad();
    }//GEN-LAST:event_bttnMasActionPerformed

    private void bttnMenosActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_bttnMenosActionPerformed
        cantidad--;

        if (cantidad < 1) {
            bttnMenos.setEnabled(false);
            campoObservaciones.setEditable(false);
            calcularMostrarCantidad();
            return;
        }
        

        if (cantidad > 0) {
            bttnMas.setEnabled(true);
            campoObservaciones.setEditable(true);
        }

        calcularMostrarCantidad();
    }//GEN-LAST:event_bttnMenosActionPerformed


