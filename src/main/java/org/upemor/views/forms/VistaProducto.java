    public VistaProducto(JDialog dialogo, Productos producto, int cantidad, String observacion) {
        initComponents();
        this.dialogo = dialogo;
        this.producto = producto;
        this.actualCantidad = cantidad;
        this.cantidad = cantidad;

        campoObservaciones.setVisible(true);
        campoObservaciones.setText(observacion);
        campoObservaciones.setEditable(cantidad > 0);
        
        if (cantidad > 50) bttnMas.setEnabled(false);
        
        if (cantidad < 1) bttnMenos.setEnabled(false);
        
        calcularMostrarCantidad();

        mostrarInfo();
    }
    
    private void calcularMostrarCantidad() {
        textoCantidad.setText(cantidad + "");
        total = cantidad * producto.getPrecio();
        textoTotal.setText(total + "");
    }

    private void mostrarInfo() {
        // Mostrar estado de disponibilidad
        String estado = producto.isDisponible() ? "Disponible" : "No Disponible";
        
        // Llenar etiquetas con los datos del producto
        textoId.setText(producto.getId() + "");
        textoNombre.setText(producto.getNombreProducto());
        campoDescripcion.setText(producto.getDescripcion());
        textoDisponible.setText(estado);
        textoPrecio.setText("Precio: $" + producto.getPrecio());
        tetxoFecha.setText(producto.getFechaRegistro() + "");
        textoPreparacion.setText("Tiempo de preparación: " + producto.getTiempoPreparacion());
        textoCategorias.setText(String.format("<html><body>Categorías: %s</body></html>", producto.getNombresCategorias()));

        // Cargar la imagen desde la ruta en un hilo separado para no bloquear la interfaz
        SwingUtilities.invokeLater(() -> {
            cargarImagenDesdeRuta(producto.getImagen());
        });
    }

    /**
     * Carga y escala la imagen del producto desde una ruta relativa para mostrarla en la etiqueta correspondiente.
     * @param rutaImagen Ruta relativa de la imagen (puede ser null)
     */
    private void cargarImagenDesdeRuta(String rutaImagen) {
        if (rutaImagen == null || rutaImagen.isEmpty()) {
            textoImagen.setIcon(null);
            textoImagen.setText("Sin imagen");
            return;
        }
        try {
            java.io.File imgFile = new java.io.File("img/" + rutaImagen);
            if (!imgFile.exists()) {
                textoImagen.setIcon(null);
                textoImagen.setText("Sin imagen");
                return;
            }
            ImageIcon icono = new ImageIcon(imgFile.getAbsolutePath());
            int ancho = textoImagen.getWidth() > 0 ? textoImagen.getWidth() : 366;
            int alto = textoImagen.getHeight() > 0 ? textoImagen.getHeight() : 380;
            Image imagenEscalada = icono.getImage().getScaledInstance(ancho, alto, Image.SCALE_SMOOTH);
            textoImagen.setIcon(new ImageIcon(imagenEscalada));
            textoImagen.setText("");
        } catch (Exception e) {
            textoImagen.setText("Error al cargar imagen");
        }
    }

