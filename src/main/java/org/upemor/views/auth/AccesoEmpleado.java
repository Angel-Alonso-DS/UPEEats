    /**
     * Acción al presionar el botón de registro.
     * Valida los campos y registra un nuevo empleado o administrador en la base de datos.
     */
    private void bttnRegistroActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_bttnRegistroActionPerformed
        try {
            String nombre = campoNombre.getText();
            String apellidoPaterno = campoApellidoPaterno.getText();
            String apellidoMaterno = campoApellidoMaterno.getText();
            String rol = cuadroRoles.getSelectedItem().toString().toLowerCase();
            String correo = campoCorreo.getText();
            String telefono = campoTelefono.getText();
            String contrasenia = new String(campoContrasenia.getPassword());
            String confirmarContra = new String(campoConfirmarContra.getPassword());
            Validadores.validarNombre(nombre);
            Validadores.validarApellido(apellidoPaterno);
            Validadores.validarApellido(apellidoMaterno);
            Validadores.validarRol(rol);
            Validadores.validarCorreo(correo);
            Validadores.validarTelefono(telefono);
            Validadores.confirmarContrasenia(contrasenia, confirmarContra);
            usuariosCTR.insertarEmpleado(new Usuarios(0, nombre, apellidoPaterno, apellidoMaterno, correo, contrasenia, telefono, true, rol, null, null));
            campoNombre.setText("");
            campoApellidoPaterno.setText("");
            campoApellidoMaterno.setText("");
            campoContrasenia.setText("");
            campoConfirmarContra.setText("");
            campoCorreo.setText("");
            campoTelefono.setText("");
            jTabbedPane1.setSelectedIndex(0);
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, e.getMessage(), "Campo invalido", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_bttnRegistroActionPerformed


    /**
     * Acción al presionar el botón de entrar.
     * Valida los campos y realiza el proceso de login del empleado o administrador.
     */
    private void bttnEntrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_bttnEntrarActionPerformed
        try {
            String correo = campoCorreoAcceso.getText();
            String contrasenia = new String(campoContraseniaAcceso.getPassword());
            Validadores.validarCorreo(correo);
            Validadores.validarContrasenia(contrasenia);
            if (framePadre == null) return;
            framePadre.mostrarDashboard(usuariosCTR.accesoEmpleado(correo, contrasenia));
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, e.getMessage(), "Campo invalido", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_bttnEntrarActionPerformed


