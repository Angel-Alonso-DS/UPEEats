    /**
     * Aplica filtros de entrada a los campos del formulario para restringir caracteres y longitud.
     */
    private void aplicarFiltros() {
        AbstractDocument docCampoCorreoAcceso = (AbstractDocument) campoCorreoAcceso.getDocument();
        AbstractDocument docContraseniaAcceso = (AbstractDocument) campoContraseniaAcceso.getDocument();
        AbstractDocument docNombre = (AbstractDocument) campoNombre.getDocument();
        AbstractDocument docApellidoPaterno = (AbstractDocument) campoApellidoPaterno.getDocument();
        AbstractDocument docApellidoMaterno = (AbstractDocument) campoApellidoMaterno.getDocument();
        AbstractDocument docTelefono = (AbstractDocument) campoTelefono.getDocument();
        AbstractDocument docContrasenia = (AbstractDocument) campoContrasenia.getDocument();
        AbstractDocument docConfirmarContra = (AbstractDocument) campoConfirmarContra.getDocument();
        docCampoCorreoAcceso.setDocumentFilter(new FiltroEntradas(50, FiltroEntradas.NO_SQL));
        docContraseniaAcceso.setDocumentFilter(new FiltroEntradas(50, FiltroEntradas.NO_SQL));
        docNombre.setDocumentFilter(new FiltroEntradas(50, FiltroEntradas.SOLO_LETRAS));
        docApellidoPaterno.setDocumentFilter(new FiltroEntradas(50, FiltroEntradas.SOLO_LETRAS));
        docApellidoMaterno.setDocumentFilter(new FiltroEntradas(50, FiltroEntradas.SOLO_LETRAS));
        docTelefono.setDocumentFilter(new FiltroEntradas(10, FiltroEntradas.SOLO_NUMEROS));
        docContrasenia.setDocumentFilter(new FiltroEntradas(50, FiltroEntradas.NO_SQL));
        docConfirmarContra.setDocumentFilter(new FiltroEntradas(50, FiltroEntradas.NO_SQL));
    }

