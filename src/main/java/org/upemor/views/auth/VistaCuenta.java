    private boolean isModoEdicion = false;


    /**
     * Cambia el modo de edición de los campos de la vista.
     * Si está en modo edición, los campos son editables y se muestra el botón cancelar.
     */
    private void cambioModoEdicion() {
        bttnCancelar.setVisible(isModoEdicion);
        campoNombre.setEditable(isModoEdicion);
        campoApellidoPaterno.setEditable(isModoEdicion);
        campoApellidoMaterno.setEditable(isModoEdicion);
        campoTelefono.setEditable(isModoEdicion);
    }

    /**
     * Acción al presionar el botón de edición.
     * Permite alternar entre modo edición y modo vista, y guardar los cambios si corresponde.
     */
    private void bttnEdicionActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_bttnEdicionActionPerformed
        if (usuario == null) return;
        if (isModoEdicion) {
            String nombre = campoNombre.getText();
            String apellidoPaterno = campoApellidoPaterno.getText();
            String apellidoMaterno = campoApellidoMaterno.getText();
            String telefono = campoTelefono.getText();
            try {
                Validadores.validarNombre(nombre);
                Validadores.validarApellido(apellidoPaterno);
                Validadores.validarApellido(apellidoMaterno);
                Validadores.validarTelefono(telefono);
                int OK = JOptionPane.showConfirmDialog(this, "Seguro?", "Editar informacion", JOptionPane.YES_NO_OPTION);
                if (OK != 0) return;
                usuariosCTR.editarUsuario(usuario.getId(), nombre, apellidoPaterno, apellidoMaterno, telefono);
                usuario = usuariosCTR.buscarPorId(usuario.getId());
                isModoEdicion = false;
                cambioModoEdicion();
            } catch (Exception e) {
                JOptionPane.showMessageDialog(this, e.getMessage(), "Campo invalido", JOptionPane.ERROR_MESSAGE);
            }
        }
        if (!isModoEdicion) {
            isModoEdicion = true;
            cambioModoEdicion();
        }
    }//GEN-LAST:event_bttnEdicionActionPerformed

    private boolean isVistaContra = false;


    /**
     * Acción al presionar el botón para mostrar/ocultar la contraseña.
     */
    private void bttnVerContraActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_bttnVerContraActionPerformed
        if (usuario == null) return;
        isVistaContra = !isVistaContra;
        if (isVistaContra) {
            bttnVerContra.setIcon(new javax.swing.ImageIcon(getClass().getResource("/icons/eye.png")));
            campoContra.setEchoChar((char) 0);
        } else {
            bttnVerContra.setIcon(new javax.swing.ImageIcon(getClass().getResource("/icons/eye-slash.png")));
            campoContra.setEchoChar('*');
        }
    }//GEN-LAST:event_bttnVerContraActionPerformed


    /**
     * Acción al presionar el botón cancelar.
     * Cancela la edición y restaura la información original.
     */
    private void bttnCancelarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_bttnCancelarActionPerformed
        isModoEdicion = false;
        cargarInfo();
        cambioModoEdicion();
    }//GEN-LAST:event_bttnCancelarActionPerformed


    /**
     * Acción al presionar el botón cerrar sesión.
     * Cierra la sesión actual y regresa a la pantalla principal.
     */
    private void bttnCerrarSesionActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_bttnCerrarSesionActionPerformed
        if (framePadre != null) {
            NotificadorGlobal.getInstancia().removerTodos();
            Main main = new Main();
            framePadre.dispose();
            main.setVisible(true);
        }
    }//GEN-LAST:event_bttnCerrarSesionActionPerformed


