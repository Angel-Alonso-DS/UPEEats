    /**
     * Asigna el usuario autenticado y actualiza la información mostrada.
     * @param usuario Usuario autenticado
     */
    public void setUsuario(Usuarios usuario) {
        this.usuario = usuario;
        boolean isEstudiante = usuario.getRol().equals("estudiante");
        textoRolMat.setText(isEstudiante? "Matricula" : "Rol");
        campoRolMat.setText(isEstudiante? usuario.getMatricula(): usuario.getRol());
        cargarInfo();
    }


    /**
     * Carga la información del usuario en los campos de la vista.
     */
    private void cargarInfo() {
        campoNombre.setText(usuario.getNombre());
        campoApellidoPaterno.setText(usuario.getApellidoPaterno());
        campoApellidoMaterno.setText(usuario.getApellidoMaterno());
        campoCorreo.setText(usuario.getCorreo());
        campoTelefono.setText(usuario.getTelefono());
        campoContra.setText(usuario.getContrasenia());
    }


